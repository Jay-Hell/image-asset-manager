import Foundation
import ImageIO

public enum AssetStoreError: Error, Equatable, LocalizedError {
    case unsupportedMediaType(String)

    public var errorDescription: String? {
        switch self {
        case .unsupportedMediaType(let mime):
            return "The library cannot store '\(mime)'."
        }
    }
}

/// What `AssetStore.store` wrote, ready to become an `Asset` row.
public struct StoredAssetFile: Sendable, Equatable {
    public let assetID: String
    public let filename: String
    public let fileURL: URL
    public let mediaType: MediaType
    public let fileHash: String
    public let width: Int?
    public let height: Int?
}

/// The one place generated bytes become a file in `assets/`, named for their MIME type.
public enum AssetStore {
    public static func store(
        _ data: Data,
        mimeType: String,
        assetID: String = UUID().uuidString,
        libraryURL: URL
    ) throws -> StoredAssetFile {
        guard let mediaType = MediaType(mimeType: mimeType) else {
            throw AssetStoreError.unsupportedMediaType(mimeType)
        }
        let filename = "\(assetID).\(mediaType.fileExtension)"
        let assetsDir = libraryURL.appending(path: "assets")
        let fileURL = assetsDir.appending(path: filename)

        try FileManager.default.createDirectory(at: assetsDir, withIntermediateDirectories: true)
        // As delivered: no re-encoding, no normalising, never over an existing file.
        try data.write(to: fileURL, options: .withoutOverwriting)

        let size = mediaType == .svg ? SVGDocument.dimensions(of: data) : pixelSize(of: data)
        return StoredAssetFile(
            assetID: assetID,
            filename: filename,
            fileURL: fileURL,
            mediaType: mediaType,
            fileHash: data.sha256,
            width: size.width,
            height: size.height
        )
    }

    /// The decoded pixel size, rather than the size that was asked for.
    static func pixelSize(of data: Data) -> (width: Int?, height: Int?) {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
        else { return (nil, nil) }
        return (props[kCGImagePropertyPixelWidth] as? Int, props[kCGImagePropertyPixelHeight] as? Int)
    }
}
